import {afterEach,expect,test,vi} from 'vitest';
import {convexTest} from 'convex-test';
import {generateKeyPair,exportPKCS8} from 'jose';
import schema from '../convex/schema';
import {api} from '../convex/_generated/api';
const modules=import.meta.glob('../convex/**/*.{ts,js}');
afterEach(()=>{vi.unstubAllGlobals();vi.unstubAllEnvs();});
test('signup starts a session without verification and password reset rejects wrong or reused codes while replacing the old password',async()=>{
 vi.stubEnv('RESEND_API_KEY','test-only-key');
 vi.stubEnv('SITE_URL','https://cheddarvox.com');
 vi.stubEnv('CONVEX_SITE_URL','https://test.convex.site');
 const {privateKey}=await generateKeyPair('RS256',{extractable:true});
 vi.stubEnv('JWT_PRIVATE_KEY',await exportPKCS8(privateKey));
 const messages:{text:string;subject:string}[]=[];
 vi.stubGlobal('fetch',vi.fn(async(_url,options)=>{messages.push(JSON.parse(options.body));return new Response(JSON.stringify({id:'test-message'}),{status:200});}));
 const t=convexTest(schema,modules);
 const email='recovery-test@example.com',oldPassword='Old-test-password-42',newPassword='New-test-password-73';
 const signIn=(params:Record<string,string>)=>t.action(api.auth.signIn,{provider:'password',params});
 const code=()=>messages.at(-1)!.text.match(/code is (\d{8})/)![1];
 expect((await signIn({flow:'signUp',email,password:oldPassword})).tokens).toBeTruthy();
 expect(messages).toHaveLength(0);
 expect((await signIn({flow:'signIn',email,password:oldPassword})).tokens).toBeTruthy();
 await signIn({flow:'reset',email});
 expect(messages.at(-1)!.subject).toMatch(/Reset/);
 const resetCode=code();
 await expect(signIn({flow:'reset-verification',email,code:'invalid-code',newPassword})).rejects.toThrow();
 expect((await signIn({flow:'reset-verification',email,code:resetCode,newPassword})).tokens).toBeTruthy();
 await expect(signIn({flow:'signIn',email,password:oldPassword})).rejects.toThrow();
 expect((await signIn({flow:'signIn',email,password:newPassword})).tokens).toBeTruthy();
 await expect(signIn({flow:'reset-verification',email,code:resetCode,newPassword:oldPassword})).rejects.toThrow();
});
