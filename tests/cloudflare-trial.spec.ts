import {test,expect} from '@playwright/test';
test('Cloudflare build plays bundled trial without a Convex video download',async({page})=>{
 test.skip(process.env.EXPECT_CLOUDFLARE_TRIAL!=='1','Run against a Cloudflare-configured build.');
 const storageDownloads:string[]=[];
 page.on('request',r=>{if(r.method()==='GET'&&/\.convex\.(cloud|site)\/api\/storage\//.test(r.url()))storageDownloads.push(r.url());});
 await page.goto('/');
 await page.getByRole('button',{name:'Try a sample video',exact:true}).click();
 const video=page.locator('video');
 await expect(video).toHaveAttribute('src',/^blob:/);
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.readyState)).toBeGreaterThanOrEqual(2);
 await page.reload();
 await expect(video).toHaveAttribute('src',/^blob:/);
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.readyState)).toBeGreaterThanOrEqual(2);
 await page.getByLabel('Seek video',{exact:true}).fill('12');
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.currentTime)).toBe(12);
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.seeking)).toBe(false);
 await page.getByRole('button',{name:'Play video',exact:true}).click();
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.currentTime)).toBeGreaterThan(12);
 await page.getByRole('button',{name:'Pause video',exact:true}).click();
 await page.getByRole('button',{name:'Next estimated frame',exact:true}).click();
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.seeking)).toBe(false);
 await page.getByLabel('Seek video',{exact:true}).fill('1');
 await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.currentTime)).toBe(1);
 expect(storageDownloads).toEqual([]);
});
